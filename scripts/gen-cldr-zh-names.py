#!/usr/bin/env python3
"""Regenerates crates/kurrency-core/src/generated/cldr_zh.rs: the Simplified
Chinese currency names from Unicode CLDR (cldr-json,
cldr-numbers-full/main/zh/currencies.json).

Usage (from the repository root):

    python3 -I scripts/gen-cldr-zh-names.py

The file is downloaded into a fresh temporary directory, checked against a
pinned SHA-256 and parsed as plain data, so the build never fetches CLDR and
the table only changes when this script is re-run with a new pin. The data
is under the Unicode License v3 (see NOTICE).

After regenerating, re-run scripts/subset-cjk-font.py: the bundled CJK font
subset must cover every character in the table.
"""

import hashlib
import json
import pathlib
import sys
import tempfile
import urllib.request

CLDR_VERSION = "48.0.0"
URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr-json/"
    f"{CLDR_VERSION}/cldr-json/cldr-numbers-full/main/zh/currencies.json"
)
SHA256 = "c23b7df1982deae53121f6665e3c27059c1e47640b167c3ce0e3bf5a64d13c8d"

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "kurrency-core" / "src" / "generated" / "cldr_zh.rs"


def fetch(url: str, sha256: str, directory: pathlib.Path) -> pathlib.Path:
    path = directory / url.rsplit("/", 1)[-1]
    with urllib.request.urlopen(url) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        sys.exit(f"{url}: sha256 {digest}, expected {sha256}")
    path.write_bytes(data)
    return path


def rust_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="kurrency-cldr-") as tmp:
        path = fetch(URL, SHA256, pathlib.Path(tmp))
        data = json.loads(path.read_text(encoding="utf-8"))
    currencies = data["main"]["zh"]["numbers"]["currencies"]
    rows = []
    for code in sorted(currencies):
        name = currencies[code].get("displayName")
        if len(code) != 3 or not code.isalpha() or not code.isupper():
            continue
        if not isinstance(name, str) or not name or name == code:
            continue
        rows.append((code, name))

    lines = [
        "//! Simplified Chinese currency names from Unicode CLDR "
        f"{CLDR_VERSION}",
        "//! (cldr-json `cldr-numbers-full/main/zh/currencies.json`, `displayName`).",
        "//!",
        "//! Copyright © 2015-2024 Unicode, Inc. Unicode License v3; see NOTICE.",
        "//! Generated by `scripts/gen-cldr-zh-names.py`; do not edit by hand.",
        "",
        "/// `(code, name)`, sorted by code.",
        "pub(crate) static NAMES: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({rust_str(code)}, {rust_str(name)})," for code, name in rows]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} names to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
